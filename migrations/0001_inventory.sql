-- Inventory schema and reproducible demonstration data (50 products + 150 transactions).
PRAGMA foreign_keys = ON;

CREATE TABLE products (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  sku TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  base_stock_quantity INTEGER NOT NULL CHECK (base_stock_quantity >= 0),
  stock_updated_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE inventory_transactions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  transaction_type TEXT NOT NULL CHECK (transaction_type IN ('inbound', 'outbound')),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  transaction_date TEXT NOT NULL,
  note TEXT CHECK (note IS NULL OR length(note) <= 200),
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX idx_inventory_transactions_product_date
  ON inventory_transactions(product_id, transaction_date);
CREATE INDEX idx_inventory_transactions_recent
  ON inventory_transactions(transaction_date DESC);

